public class MathPractice {
   public static void main(String[] args) {
      System.out.println(Math.abs(-5));   //absolute value
      System.out.println(Math.pow(2, 5));   // power of _ to the _
      System.out.println(Math.sqrt(2));   //square root
      System.out.println(Math.random());   //0-1 random number double
      System.out.println((int) (Math.random()*8)+3);   
   }
}